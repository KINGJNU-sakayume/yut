export function formatNumber(n: number): string {
  return Math.round(n).toLocaleString('ko-KR')
}

export function formatMult(n: number): string {
  const fixed = Number.isInteger(n) ? String(n) : n.toFixed(2).replace(/0+$/, '').replace(/\.$/, '')
  return `×${fixed}`
}
