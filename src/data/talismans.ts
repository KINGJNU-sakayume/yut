export type TalismanPool = 'shop' | 'market' | 'blessing'

export interface TalismanDef {
  id: string
  name: string
  glyph: string
  rarity: Rarity
  price: number
  tags: TalismanTag[]
  /** When it fires (발동 시점). */
  trigger: string
  /** Condition (조건). */
  condition: string
  /** What it does (효과). */
  effect: string
  /** Cursed downside, always shown before purchase. */
  downside?: string
  effects: EffectSpec[]
  /** Current growing value / charges for tooltips. */
  stateText?: (inst: TalismanInstance) => string | null
  pool: TalismanPool
  /** Requires this meta unlock to appear. */
  unlock?: string
}

